"""Aggregate exploration of the tracking and Smart Tagging. Prints summary statistics only --
no rows, no frames -- and writes the same text to notes/exploration.md.

    python -m src.explore
"""

import io
import os
import sys

import numpy as np

from src import atd, features, tagging
from games import GAME, half_video_blocks

ROOT = atd.ROOT
OUT = os.path.join(ROOT, "notes", "exploration.md")
FPS = 25


def runs(mask):
    """Lengths of runs of True in a boolean array."""
    padded = np.concatenate(([False], mask, [False]))
    edges = np.flatnonzero(padded[1:] != padded[:-1])
    return edges[1::2] - edges[::2]


def pct(values, qs=(5, 25, 50, 75, 95, 99)):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if not len(values):
        return "n/a"
    return "  ".join("p{}={:.2f}".format(q, np.percentile(values, q)) for q in qs)


def main():
    buf = io.StringIO()

    def say(text=""):
        print(text)
        buf.write(text + "\n")

    a = atd.load()
    f = features.compute(a)
    n = len(a["bx"])
    graded = np.zeros(n, bool)
    for _, first, last in half_video_blocks(GAME):
        graded[first:last + 1] = True

    say("# Exploration (aggregates only)")
    say()
    say("Generated by `python -m src.explore`. Graded frames = the two halves from DATA.md.")
    say()
    say("## Ball visibility")
    seen = np.isfinite(a["bx"])
    say("- ball seen on {:.1f}% of all frames, {:.1f}% of graded frames".format(
        100 * seen.mean(), 100 * seen[graded].mean()))
    gaps = []
    for _, first, last in half_video_blocks(GAME):
        gaps.extend(runs(~seen[first:last + 1]))
    gaps = np.array(gaps)
    say("- graded ball-missing gaps: {} gaps, length in seconds {}".format(
        len(gaps), pct(gaps / FPS)))
    for limit in (1, 3, 10, 30):
        share = gaps[gaps > limit * FPS].sum() / max(gaps.sum(), 1)
        say("  - share of missing frames inside gaps longer than {:>2} s: {:.1f}%".format(
            limit, 100 * share))
    say()

    say("## Ball speed (graded frames, ball seen)")
    say("- from position differences, 0.2 s smoothed (m/s): {}".format(
        pct(f["ball_speed"][graded])))
    say("- tracker speed field (m/s): {}".format(pct(a["bs"][graded])))
    say()

    say("## Ball outside the pitch (graded frames, ball seen)")
    L, W = features.PITCH
    bx, by = a["bx"][graded & seen], a["by"][graded & seen]
    for margin in (0.0, 1.0, 3.0):
        out = (bx < -margin) | (bx > L + margin) | (by < -margin) | (by > W + margin)
        say("- beyond the lines by more than {:.0f} m: {:.2f}% of seen frames".format(
            margin, 100 * out.mean()))
    say()

    say("## Players")
    say("- tracked objects per graded frame: mean {:.1f}, {}".format(
        f["n_players"][graded].mean(), pct(f["n_players"][graded])))
    say("- mean player speed per graded frame (m/s): {}".format(
        pct(f["mean_speed"][graded])))
    say("- deciles of mean player speed (m/s): {}".format(
        "  ".join("{:.2f}".format(v) for v in np.nanpercentile(f["mean_speed"][graded],
                                                              np.arange(10, 100, 10)))))
    say("- nearest player to ball (m), graded+seen: {}".format(
        pct(np.minimum(f["d_home"], f["d_away"])[graded & seen])))
    say("- |away - home| nearest-distance margin (m), graded+seen: {}".format(
        pct(np.abs(f["margin"])[graded & seen])))
    low = f["mean_speed"] < 1.3
    say("- graded frames with mean player speed < 1.3 m/s: {:.1f}%; of those, ball missing: "
        "{:.1f}%".format(100 * low[graded].mean(), 100 * (~seen[graded & low]).mean()))
    say()

    say("## Smart Tagging")
    events = tagging.load()
    codes = {}
    for e in events:
        codes[e["code"]] = codes.get(e["code"], 0) + 1
    say("- {} instances".format(len(events)))
    for code in sorted(codes, key=lambda c: -codes[c]):
        durs = [(e["end_frame"] - e["start_frame"]) / FPS for e in events if e["code"] == code]
        say("  - {:<30} n={:>3}  duration s: median {:.1f}  p90 {:.1f}".format(
            code, codes[code], np.median(durs), np.percentile(durs, 90)))
    say("- set pieces by type:")
    types = {}
    for e in events:
        if (e["code"] or "").strip().lower() == "set pieces":
            types.setdefault(e["tags"].get("Type") or "?", []).append(
                (e["end_frame"] - e["start_frame"]) / FPS)
    for t in sorted(types, key=lambda t: -len(types[t])):
        say("  - {:<22} n={:>3}  duration s: median {:.1f}  min {:.1f}  max {:.1f}".format(
            t, len(types[t]), np.median(types[t]), min(types[t]), max(types[t])))
    covered = np.zeros(n, bool)
    for e in events:
        if (e["code"] or "").strip().lower() == "set pieces":
            covered[max(e["start_frame"], 0):e["end_frame"]] = True
    say("- graded frames inside a SET PIECES interval: {:.1f}%".format(
        100 * covered[graded].mean()))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(buf.getvalue())
    print("\nwrote {}".format(os.path.relpath(OUT, ROOT)), file=sys.stderr)


if __name__ == "__main__":
    main()
